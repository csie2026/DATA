"""CSV, 고정된 seed 식별자, 경로를 검증하는 공용 도구."""
import csv
import hashlib
import json
import math
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDS = {
    'mountain_id': 'mountain_id', 'source': 'source', 'name': 'name',
    'start_name': 'start_name', 'start_lat': 'start_lat', 'start_lon': 'start_lng',
    'start_elev_m': 'start_elevation', 'climb_m': 'climb', 'length_km': 'length_km',
    'up_min': 'up_min', 'down_min': 'down_min', 'difficulty': 'difficulty', 'risk': 'risk',
}
NUMBERS = {'mountain_id', 'start_lat', 'start_lon', 'start_elev_m', 'climb_m',
           'length_km', 'up_min', 'down_min'}
DIFFICULTY = {'쉬움': 'EASY', '보통': 'NORMAL', '어려움': 'HARD'}


def read_csv(path):
    with Path(path).open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_identity(path=None):
    with Path(path or ROOT / 'data/seed_identity.json').open(encoding='utf-8') as stream:
        identity = json.load(stream)
    ids = [r['id'] for r in identity['courses']]
    if (identity.get('version') != 1 or len(identity['mountain_ids']) != 140
            or len(set(identity['mountain_ids'])) != 140 or any(i <= 0 for i in identity['mountain_ids'])
            or len(ids) != 420 or sorted(ids) != list(range(1, 421))
            or len({(r['mountain_id'], r['name']) for r in identity['courses']}) != 420
            or any(r['mountain_id'] not in identity['mountain_ids'] for r in identity['courses'])):
        raise ValueError('seed_identity.json의 기준 ID 집합이 올바르지 않습니다.')
    if (len(identity['mountains']) != 140
            or {r['id'] for r in identity['mountains']} != set(identity['mountain_ids'])
            or len({r['name'] for r in identity['mountains']}) != 140
            or set(identity['seed_sha256']) != {'V2__mountains.sql', 'V3__courses.sql'}
            or any(not re.fullmatch('[0-9a-f]{64}', value) for value in identity['seed_sha256'].values())):
        raise ValueError('seed_identity.json의 산 대응표 또는 seed 체크섬이 올바르지 않습니다.')
    return identity


def assign_course_ids(rows, identity):
    baseline = {(r['mountain_id'], r['name']): r for r in identity['courses']}
    result, seen = [], set()
    for row in rows:
        key = (int(row['mountain_id']), row['name'])
        if key in seen or key not in baseline:
            raise ValueError(f'코스 식별자가 중복되거나 기준에 없습니다: {key}')
        seen.add(key)
        old = baseline[key]
        if (row['source'].upper() != old['source']
                or float(row['start_lat']) != old['start_lat']
                or float(row['start_lon']) != old['start_lon']):
            raise ValueError(f'코스 출처 또는 출발점이 바뀌었습니다. ID 대응을 검토하세요: {key}')
        result.append((old['id'], row))
    if seen != baseline.keys():
        raise ValueError(f'코스 기준 420개와 다릅니다: 현재 {len(seen)}개')
    return sorted(result, key=lambda pair: pair[0])


def validate_scope(mountains, courses, identity):
    ids = [int(r['id']) for r in mountains]
    if len(ids) != 140 or len(set(ids)) != 140 or set(ids) != set(identity['mountain_ids']):
        raise ValueError('산 140개의 기존 ID 집합이 변경되었습니다.')
    names = {r['id']: r['name'] for r in identity['mountains']}
    if any(names.get(int(r['id'])) != r['name'] for r in mountains):
        raise ValueError('산 ID와 이름의 기존 대응이 변경되었습니다. 별도 검토가 필요합니다.')
    return assign_course_ids(courses, identity)


def load_seed(seed_dir):
    # 실제 DB에 연결하지 않고 V2·V3의 제한된 DDL만 메모리에서 해석한다.
    with sqlite3.connect(':memory:') as db:
        db.row_factory = sqlite3.Row
        for filename in ('V2__mountains.sql', 'V3__courses.sql'):
            text = (Path(seed_dir) / filename).read_text(encoding='utf-8')
            text = text.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY')
            text = re.sub(r'ALTER TABLE (?:mountains|courses) ALTER COLUMN id RESTART WITH \d+;', '', text)
            db.executescript(text)
        return ([dict(r) for r in db.execute('select * from mountains order by id')],
                [dict(r) for r in db.execute('select * from courses order by id')])


def distance(lat1, lon1, lat2, lon2):
    x = math.radians(lon2 - lon1) * math.cos(math.radians((lat1 + lat2) / 2))
    return 6371000 * math.hypot(x, math.radians(lat2 - lat1))


def validate_line(geometry, row, mountain):
    if not isinstance(geometry, dict):
        raise ValueError('경로 geometry가 객체가 아닙니다.')
    points = geometry.get('coordinates')
    if geometry.get('type') != 'LineString' or not isinstance(points, list) or len(points) < 2:
        raise ValueError('경로는 두 점 이상의 LineString이어야 합니다.')
    for point in points:
        if (not isinstance(point, (list, tuple)) or len(point) != 2
                or any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in point)
                or not (126.3 <= point[0] <= 127.9 and 36.8 <= point[1] <= 38.4)):
            raise ValueError('경로에 잘못된 [경도, 위도] 좌표가 있습니다.')
    start = distance(float(row['start_lat']), float(row['start_lon']), points[0][1], points[0][0])
    end = distance(float(mountain['summit_lat']), float(mountain['summit_lon']), points[-1][1], points[-1][0])
    if start > 60 or end > 300:
        raise ValueError(f'경로의 출발점 또는 정상 연결 범위를 벗어났습니다: {start:.1f}m / {end:.1f}m')
    return end


def validate_features(features, rows, mountains, name='courses'):
    if not isinstance(features, list) or len(features) != len(rows):
        raise ValueError(f'{name}.geojson과 CSV의 개수가 다릅니다.')
    key = (lambda r: (str(r['mountain_id']), r['name'])) if name == 'courses' else (lambda r: str(r['id']))
    expected = {key(r): r for r in rows}
    if len(expected) != len(rows):
        raise ValueError(f'{name} CSV에 중복 식별자가 있습니다.')
    seen = set()
    for feature in features:
        if (not isinstance(feature, dict) or feature.get('type', 'Feature') != 'Feature'
                or not isinstance(feature.get('properties'), dict)
                or not isinstance(feature.get('geometry'), dict)):
            raise ValueError(f'{name}.geojson의 Feature 형식이 잘못되었습니다.')
        props = {k: str(v) for k, v in feature['properties'].items()}
        ident = key(props)
        if ident in seen or ident not in expected or props != {k: str(v) for k, v in expected[ident].items()}:
            raise ValueError(f'{name}.geojson의 속성과 CSV가 다릅니다: {ident}')
        seen.add(ident)
        if name == 'courses':
            validate_line(feature['geometry'], props, mountains[str(props['mountain_id'])])
        else:
            # 구간도 같은 좌표 검증을 사용하되 정상 연결 조건은 적용하지 않는다.
            points = feature['geometry'].get('coordinates', [])
            if feature['geometry'].get('type') != 'LineString' or len(points) < 2:
                raise ValueError('구간 경로가 올바른 LineString이 아닙니다.')
            for p in points:
                if (not isinstance(p, list) or len(p) != 2
                        or any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in p)
                        or not (126.3 <= p[0] <= 127.9 and 36.8 <= p[1] <= 38.4)):
                    raise ValueError('구간 경로 좌표가 올바르지 않습니다.')


def normalized_course(row):
    result = {}
    for src, dest in FIELDS.items():
        value = row[src]
        if src == 'difficulty':
            value = DIFFICULTY[value]
        elif src == 'source':
            value = value.upper()
        elif value in ('', None):
            value = None
        elif src in NUMBERS:
            value = float(value)
        result[dest] = value
    return result


def compare_seed(data_dir, seed_dir, identity_path=None):
    import build_seed_sql as generator
    data_dir, seed_dir = Path(data_dir), Path(seed_dir)
    identity = load_identity(identity_path)
    mountains, courses = read_csv(data_dir / 'mountains.csv'), read_csv(data_dir / 'courses.csv')
    assigned = validate_scope(mountains, courses, identity)
    for name, expected in identity['seed_sha256'].items():
        if digest(seed_dir / name) != expected:
            raise ValueError(f'기존 Flyway 파일이 기준과 다릅니다: {name}')
    sm, sc = load_seed(seed_dir)
    if {r['id'] for r in sm} != set(identity['mountain_ids']) or len(sm) != 140 or len(sc) != 420:
        raise ValueError('seed의 산·코스 개수가 기준과 다릅니다.')
    by_id = {r['id']: r for r in sm}
    desc = {r['name']: r['description'] for r in read_csv(data_dir / 'mountain_descriptions.csv')}
    for row in mountains:
        city = generator.CITY_OVERRIDE.get(row['name'], row['sigungu_name'])
        lat, lng = float(row['summit_lat']), float(row['summit_lon'])
        nx, ny = generator.kma_grid(lat, lng)
        expected = dict(id=int(row['id']), name=row['name'], region=generator.REGION_OF[city],
                        sigungu_code=generator.SIGUNGU_CODE[city], sigungu_name=city,
                        address=' '.join(row['address'].split()), height=float(f"{float(row['height']):.1f}"),
                        lat=lat, lng=lng, grid_nx=nx, grid_ny=ny, description=desc[row['name']])
        if expected != by_id[expected['id']]:
            raise ValueError(f'산 CSV와 seed가 다릅니다: {row["id"]} {row["name"]}')
    cs = {r['id']: r for r in sc}
    gaps = []
    for ident, row in assigned:
        seed = cs[ident]
        if normalized_course(row) != {key: seed[key] for key in FIELDS.values()}:
            raise ValueError(f'코스 CSV와 seed가 다릅니다: {ident} {row["name"]}')
        m = by_id[seed['mountain_id']]
        gap = validate_line({'type': 'LineString', 'coordinates': json.loads(seed['path'])}, row,
                            {'summit_lat': m['lat'], 'summit_lon': m['lng']})
        if gap > 30:
            gaps.append({'course_id': ident, 'mountain_id': m['id'], 'mountain_name': m['name'],
                         'course_name': row['name'], 'gap_m': round(gap, 2)})
    return {'status': '통과 (CSV·고정 seed 기준, 운영 DB·원본 GeoJSON 제외)',
            'mountains': len(sm), 'courses': len(sc), 'covered_mountains': len({r['mountain_id'] for r in sc}),
            'difficulty': {label: sum(r['difficulty'] == code for r in sc) for label, code in DIFFICULTY.items()},
            'endpoint_gap_over_30m': gaps,
            'missing_geojson': [name for name in ('courses.geojson', 'trails.geojson') if not (data_dir / name).exists()]}


def require_empty_output(out_dir, protected):
    out = Path(out_dir).resolve()
    if any(p.name.lower() == 'migration' and p.parent.name.lower() == 'db' for p in (out, *out.parents)):
        raise ValueError('Flyway migration 폴더에 직접 출력할 수 없습니다.')
    for item in protected:
        item = Path(item).resolve()
        if out == item or item in out.parents:
            raise ValueError('기존 DATA 또는 BE migration 폴더에 출력할 수 없습니다. 별도 빈 폴더를 지정하세요.')
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise ValueError('출력 폴더는 비어 있어야 합니다. 기존 파일을 덮어쓰지 않습니다.')
    return out
